/**
 * This lab's hand-picked "simple" equivalent-fraction pairs, every one
 * within the 2/3/4/6/8 denominator set — the plan explicitly left the exact
 * list to the builder's judgment (3.NF.3a-b says "simple cases" without
 * enumerating them). Deliberately NOT generated by a general n×k/d×k
 * multiplier the way MG9_IntroToFractionsLab's EquivalentFractions unit
 * does — that general scaling reasoning is this lab's own hard scope
 * boundary against MG9 (see plan's "Relationship to existing labs"), so
 * every pair here is a fixed, specific fact pair instead.
 */
export const EQUIVALENT_PAIRS: [number, number, number, number][] = [
  [1, 2, 2, 4],
  [1, 2, 3, 6],
  [1, 2, 4, 8],
  [1, 3, 2, 6],
  [1, 4, 2, 8],
  [2, 3, 4, 6],
  [3, 4, 6, 8],
  [2, 4, 4, 8],
];

/**
 * Near-miss pairs that LOOK like they could be equivalent (both simple
 * fractions within the same denominator set) but genuinely aren't — the
 * plan's own example is 1/3 vs 2/4. Every entry here was checked by hand to
 * NOT be numerically equal, so the "nonexample" bucket always has a true
 * negative to present, never an accidental match.
 */
export const NEAR_MISS_PAIRS: [number, number, number, number][] = [
  [1, 3, 2, 4],
  [1, 2, 2, 6],
  [2, 3, 3, 6],
  [1, 4, 2, 6],
  [3, 4, 4, 6],
  [1, 2, 3, 8],
  [2, 4, 3, 8],
  [1, 3, 3, 8],
];

// ============================================================================
// CHECK FOR UNDERSTANDING — mandatory gate before Practice unlocks
// ============================================================================

/**
 * Four fixed questions covering all four bucket "shapes" at once, with the
 * exact same numbers used throughout this file's own CFU/Explore examples.
 * Q1 is the reasoning question (equivalence as "same point," not a
 * manipulation trick — the point this unit's scope note insists on, since
 * the general n×k/d×k rule is deferred to MG9). Q2 is the nonexample trap
 * the plan calls out directly (1/3 vs 2/4). Q3 is the production direction
 * (find a missing numerator), via the Stepper+Check pattern. Q4 confirms a
 * genuine positive case isn't mistakenly rejected either.
 */
function EquivalentFractionsCheck({ onComplete }: { onComplete?: () => void }) {
  const [q1, setQ1] = useState<string | null>(null);
  const q1Done = q1 === "point";

  const [q2, setQ2] = useState<string | null>(null);
  const q2Done = q2 === "no";

  const [numerator, setNumerator] = useState(0);
  const [q3Checked, setQ3Checked] = useState(false);
  const q3Done = q3Checked && numerator === 2;

  const [q4, setQ4] = useState<string | null>(null);
  const q4Done = q4 === "yes";

  const allDone = q1Done && q2Done && q3Done && q4Done;
  useEffect(() => {
    if (allDone) onComplete?.();
  }, [allDone, onComplete]);

  return (
    <div className="align-drill">
      <p className="intro-gate-title">Quick check: let's make sure "equivalent" means the same point, before you try practice problems.</p>

      <div className="align-stack-wrap">
        <p>
          <b>1.</b> <EquivalentBars n1={1} d1={2} n2={2} d2={4} width={260} /> Why are 1/2 and 2/4 equivalent?
        </p>
        <div className="control-row">
          {[
            { id: "point", label: "They land on the exact same point on the number line" },
            { id: "count", label: "Because 2/4 has more pieces shaded, so it must be the same or bigger" },
          ].map((opt) => (
            <button key={opt.id} type="button" className={`btn ghost ${q1 === opt.id ? "pressed" : ""}`} disabled={q1Done} onClick={() => setQ1(opt.id)}>
              {opt.label}
            </button>
          ))}
        </div>
        {q1 && (
          <p className={`feedback ${q1Done ? "good" : "bad"}`} role="alert">
            {q1Done ? "Correct — same point, same amount, just cut into a different number of pieces." : "Not quite — think about where each fraction would land if you marked it on a number line."}
          </p>
        )}
      </div>

      <div className="align-stack-wrap">
        <p>
          <b>2.</b> <EquivalentBars n1={1} d1={3} n2={2} d2={4} width={260} /> Are 1/3 and 2/4 equivalent?
        </p>
        <div className="control-row">
          {[
            { id: "no", label: "No — they don't line up to the same amount" },
            { id: "yes", label: "Yes — they're both simple fractions, so they must match" },
          ].map((opt) => (
            <button key={opt.id} type="button" className={`btn ghost ${q2 === opt.id ? "pressed" : ""}`} disabled={q2Done} onClick={() => setQ2(opt.id)}>
              {opt.label}
            </button>
          ))}
        </div>
        {q2 && (
          <p className={`feedback ${q2Done ? "good" : "bad"}`} role="alert">
            {q2Done ? "Correct — the shaded amounts don't line up, so they're NOT equivalent, even though both are simple fractions." : "Not quite — look closely at the bars above. Do the shaded widths actually match?"}
          </p>
        )}
      </div>

      <div className="align-stack-wrap">
        <p>
          <b>3.</b> Use the stepper to find the missing numerator: 1/4 = ?/8.
        </p>
        <div className="control-row">
          <Stepper label="Numerator" value={numerator} min={0} max={8} onChange={(v) => { setNumerator(v); setQ3Checked(false); }} tone="b" />
        </div>
        <EquivalentBars n1={1} d1={4} n2={numerator} d2={8} width={260} />
        <button className="btn primary" type="button" disabled={q3Done} onClick={() => setQ3Checked(true)}>
          Check my work
        </button>
        {q3Checked && (
          <p className={`feedback ${q3Done ? "good" : "bad"}`} role="alert">
            {q3Done ? "Correct — 1/4 = 2/8." : "Not quite — watch the bars above line up as you change the numerator."}
          </p>
        )}
      </div>

      <div className="align-stack-wrap">
        <p>
          <b>4.</b> <EquivalentBars n1={2} d1={3} n2={4} d2={6} width={260} /> Are 2/3 and 4/6 equivalent?
        </p>
        <div className="control-row">
          {[
            { id: "yes", label: "Yes — they line up to the exact same amount" },
            { id: "no", label: "No — they're split into a different number of pieces, so they can't be the same" },
          ].map((opt) => (
            <button key={opt.id} type="button" className={`btn ghost ${q4 === opt.id ? "pressed" : ""}`} disabled={q4Done} onClick={() => setQ4(opt.id)}>
              {opt.label}
            </button>
          ))}
        </div>
        {q4 && (
          <p className={`feedback ${q4Done ? "good" : "bad"}`} role="alert">
            {q4Done ? "Correct — a different number of pieces doesn't mean a different amount." : "Not quite — look at how much of each bar is shaded, not how many pieces each is split into."}
          </p>
        )}
      </div>
    </div>
  );
}

// ============================================================================
// EXPLORE
// ============================================================================

function Explore({ onIntroDone }: { onIntroDone?: () => void }) {
  const introActive = !!onIntroDone;
  const [showCheck, setShowCheck] = useState(false);
  const [pairIdx, setPairIdx] = useState(0);
  const [showNearMiss, setShowNearMiss] = useState(false);
  const [n1, d1, n2, d2] = showNearMiss ? NEAR_MISS_PAIRS[pairIdx] : EQUIVALENT_PAIRS[pairIdx];

  return (
    <div style={{ display: "flex", flexDirection: "column", gap: 16 }}>
      {!introActive && (
        <button
          type="button"
          className="btn ghost"
          style={{ width: "fit-content", ...(showCheck ? { background: "var(--good-soft)", borderColor: "var(--good)" } : undefined) }}
          onClick={() => setShowCheck((v) => !v)}
        >
          Quick Check
        </button>
      )}
      {(introActive || showCheck) && <EquivalentFractionsCheck onComplete={onIntroDone} />}
      <p>Two fractions are equivalent when they name the exact same point on the number line — even written with totally different numbers.</p>
      <Segmented
        label="Pair"
        value={String(pairIdx)}
        onChange={(v) => setPairIdx(Number(v))}
        options={(showNearMiss ? NEAR_MISS_PAIRS : EQUIVALENT_PAIRS).map((p, i) => ({ id: String(i), label: `${p[0]}/${p[1]} & ${p[2]}/${p[3]}` }))}
      />
      <button type="button" className="btn ghost" style={{ width: "fit-content" }} onClick={() => { setShowNearMiss((v) => !v); setPairIdx(0); }}>
        {showNearMiss ? "Show a TRUE equivalent pair instead" : "Show a pair that LOOKS equivalent but isn't"}
      </button>
      <EquivalentBars n1={n1} d1={d1} n2={n2} d2={d2} />
      <StackedNumberLines n1={n1} d1={d1} n2={n2} d2={d2} />
      <p className="muted small">
        {n1 * d2 === n2 * d1
          ? `${n1}/${d1} and ${n2}/${d2} land on the exact same point — they're equivalent.`
          : `${n1}/${d1} and ${n2}/${d2} land on DIFFERENT points — even though both look like simple fractions, they're NOT equivalent.`}
      </p>
    </div>
  );
}

// ============================================================================
// PROBLEM TYPE 1 — recognize a true equivalent pair
// ============================================================================

function recognizeProblem(): Problem {
  const [n1, d1, n2, d2] = pick(EQUIVALENT_PAIRS);
  return {
    title: "Spot equivalent fractions",
    bucket: "recognize",
    story: "",
    visual: () => <EquivalentBars n1={n1} d1={d1} n2={n2} d2={d2} />,
    steps: [
      choice(
        {
          prompt: "Look at the right edge of the shaded part in each bar. Do they end at the same place?",
          hint: "Follow the end of the top bar's shading straight down to the bottom bar.",
          explain: "Yes — the shading ends at exactly the same place.",
        },
        "Yes, at the same place",
        ["No, at different places"]
      ),
      choice(
        {
          prompt: `Are ${n1}/${d1} and ${n2}/${d2} equivalent?`,
          hint: "Compare how much of each bar is shaded, not how many pieces each is split into.",
          explain: `${n1}/${d1} and ${n2}/${d2} shade the exact same amount, just cut into a different number of pieces — they're equivalent.`,
        },
        "Yes — they line up to the exact same amount",
        ["No — they're split into a different number of pieces, so they can't be the same"]
      ),
    ],
    wrapUp: `${n1}/${d1} = ${n2}/${d2}.`,
  };
}

// ============================================================================
// PROBLEM TYPE 2 — generate a missing numerator
// ============================================================================

function generateProblem(): Problem {
  const [n1, d1, n2, d2] = pick(EQUIVALENT_PAIRS);
  return {
    title: "Find the equivalent fraction",
    bucket: "generate",
    story: `${n1}/${d1} is equivalent to ?/${d2}. What's the missing numerator?`,
    visual: (done: number) => <EquivalentBars n1={n1} d1={d1} n2={done >= 2 ? n2 : 0} d2={d2} />,
    steps: [
      {
        kind: "number",
        prompt: `Look at the bars. How many of the bottom bar's small pieces line up under ONE of the top bar's pieces?`,
        hint: "Find one top piece and count the small pieces directly underneath it.",
        explain: `${d2 / d1} small pieces fit under each big piece.`,
        answer: d2 / d1,
      },
      {
        kind: "number",
        prompt: `What numerator makes ?/${d2} equivalent to ${n1}/${d1}?`,
        hint: "Look at the bars — how much of the bottom bar needs to be shaded to match the top bar's amount?",
        explain: `${n1}/${d1} = ${n2}/${d2} — the same amount, cut into ${d2} pieces instead of ${d1}.`,
        answer: n2,
      },
    ],
    wrapUp: `${n1}/${d1} = ${n2}/${d2}.`,
  };
}

// ============================================================================
// PROBLEM TYPE 3 — explain why two fractions are equivalent
// ============================================================================

function explainProblem(): Problem {
  const [n1, d1, n2, d2] = pick(EQUIVALENT_PAIRS);
  return {
    title: "Why are they equivalent?",
    bucket: "explain",
    story: "",
    visual: () => <StackedNumberLines n1={n1} d1={d1} n2={n2} d2={d2} />,
    steps: [
      choice(
        {
          prompt: "Both lines are the same length from 0 to 1. Where do the two dots land?",
          hint: "Is one dot directly above the other?",
          explain: "At exactly the same spot.",
        },
        "At exactly the same spot",
        [`${n1}/${d1} is to the left of ${n2}/${d2}`, `${n1}/${d1} is to the right of ${n2}/${d2}`]
      ),
      choice(
        {
          prompt: `Why are ${n1}/${d1} and ${n2}/${d2} equivalent?`,
          hint: "Look at where each one lands on the number line.",
          explain: `They land on the exact same point on the number line — same amount, different number of pieces.`,
        },
        "They land on the exact same point on the number line",
        [`Because ${n1} + ${d1} equals ${n2} + ${d2}`, "Because they're both shaded in the same color"]
      ),
    ],
    wrapUp: `${n1}/${d1} and ${n2}/${d2} are the same point on the number line.`,
  };
}

// ============================================================================
// PROBLEM TYPE 4 — non-equivalent near-miss (trap)
// ============================================================================

function nonExampleProblem(): Problem {
  const [n1, d1, n2, d2] = pick(NEAR_MISS_PAIRS);
  return {
    title: "Spot the near-miss",
    bucket: "nonexample",
    story: "",
    visual: () => <EquivalentBars n1={n1} d1={d1} n2={n2} d2={d2} />,
    steps: [
      choice(
        {
          prompt: "Look at the right edge of the shaded part in each bar. Do they end at the same place?",
          hint: "Follow the end of the top bar's shading straight down to the bottom bar.",
          explain: "No — the shading ends at different places.",
        },
        "No, at different places",
        ["Yes, at the same place"]
      ),
      choice(
        {
          prompt: `Are ${n1}/${d1} and ${n2}/${d2} equivalent?`,
          hint: "Compare the shaded widths carefully — do they really match?",
          explain: `${n1}/${d1} and ${n2}/${d2} shade different amounts — they are NOT equivalent, even though both are simple fractions.`,
        },
        "No — they don't line up to the same amount",
        ["Yes — they're both simple fractions, so they must match"]
      ),
    ],
    wrapUp: `${n1}/${d1} and ${n2}/${d2} are NOT equivalent.`,
  };
}

